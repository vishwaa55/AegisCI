"""
Security Data Models for AegisCI Security Finding Intake & Multi-Agent Debate.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class SecurityFinding(BaseModel):
    """Normalized security finding from static analysis (Semgrep)."""
    id: str = Field(..., description="Unique finding ID e.g. finding-semgrep-0")
    rule_id: str = Field(..., description="Semgrep rule identifier, e.g. python.lang.security.audit.sqli")
    severity: str = Field(..., description="ERROR, WARNING, INFO")
    file_path: str = Field(..., description="Normalized repository relative file path")
    start_line: int = Field(..., description="Starting line number")
    end_line: int = Field(..., description="Ending line number")
    start_col: Optional[int] = Field(default=None, description="Starting column number")
    end_col: Optional[int] = Field(default=None, description="Ending column number")
    message: str = Field(..., description="Security explanation or recommendation from rule")
    code_snippet: str = Field(default="", description="Source code lines flagged by rule")
    cwe: Optional[str] = Field(default=None, description="CWE category, e.g. CWE-89")
    owasp: Optional[str] = Field(default=None, description="OWASP category, e.g. A03:2021-Injection")


class AttackerAssessment(BaseModel):
    """Structured security assessment produced by the Attacker Agent."""
    finding_id: str
    exploitability: str = Field(
        ...,
        description="'unlikely', 'plausible', or 'confirmed'"
    )
    attack_vector: str = Field(..., description="Description of the attack vector")
    attacker_controlled_inputs: List[str] = Field(
        default_factory=list,
        description="List of inputs controlled or influenced by external actors"
    )
    trust_boundaries: str = Field(..., description="Trust boundary crossed by untrusted input")
    exploit_scenario: str = Field(..., description="Step-by-step hypothetical or demonstrated exploit path")
    evidence_vs_assumptions: str = Field(
        ...,
        description="Clear distinction between confirmed code evidence and assumptions"
    )
    confidence: float = Field(default=0.7, ge=0.0, le=1.0)


class DefenderProposal(BaseModel):
    """Candidate patch and rationale generated by Defender A or Defender B."""
    defender_id: str = Field(..., description="'defender_a' or 'defender_b'")
    strategy_name: str = Field(..., description="e.g. 'Strict Input Sanitization' or 'Safe API Substitution'")
    patch_diff: str = Field(..., description="Unified diff patch fixing the vulnerability")
    security_rationale: str = Field(..., description="Why this patch neutralizes the attacker exploit path")
    potential_side_effects: str = Field(..., description="Trade-offs, performance or backward compatibility notes")
    critique_of_counterpart: Optional[str] = Field(
        default=None,
        description="Constructive critique of the other defender's approach in debate rounds"
    )


class JudgeDecision(BaseModel):
    """Evaluation verdict produced by the Judge Agent."""
    status: str = Field(..., description="'accepted', 'rejected', or 'escalated'")
    selected_defender: Optional[str] = Field(
        default=None,
        description="'defender_a', 'defender_b', or 'synthesized'"
    )
    selected_patch: Optional[str] = Field(default=None, description="Winning unified diff patch")
    rationale: str = Field(..., description="Judge rationale comparing both defenders")
    semgrep_verified: bool = Field(default=False, description="Whether Semgrep scan passed on the patch")
    tests_verified: bool = Field(default=False, description="Whether test suite passed on the patch")
    regression_detected: bool = Field(default=False, description="Whether any functional regression occurred")
    round_number: int = Field(default=1, description="Debate round number (1 to 3)")
    validation_evidence: str = Field(default="", description="Logs and test/scan outputs from isolated sandbox")

